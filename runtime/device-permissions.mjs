import fs from 'node:fs';

export function validateWakeDevice(stableWakeDevice, wakeDevice, realpathSync = fs.realpathSync) {
  let resolved;
  try { resolved = realpathSync(stableWakeDevice); } catch { throw new Error(`Stable BMI323 wake device is missing: ${stableWakeDevice}`); }
  if (resolved !== wakeDevice) throw new Error(`Stable wake device does not identify the BMI323 input: ${stableWakeDevice}`);
}

export function sensorSandbox(root, device, stableWakeDevice) {
  return `# Generated by runtime/permissions.mjs from sensor discovery; do not edit.\n[Service]\nReadWritePaths=${root}\nDeviceAllow=${device} r\nDeviceAllow=${stableWakeDevice} r\n`;
}
